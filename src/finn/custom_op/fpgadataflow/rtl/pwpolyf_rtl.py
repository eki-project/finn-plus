import numpy as np
from onnx import NodeProto
from pathlib import Path
from qonnx.core.datatype import DataType
from qonnx.core.modelwrapper import ModelWrapper
from typing import TYPE_CHECKING, cast

from finn.custom_op.fpgadataflow.pwpolyf import NodeAttrTypes, PWPolyF
from finn.custom_op.fpgadataflow.rtl import register_custom_op
from finn.custom_op.fpgadataflow.rtlbackend import RTLBackend
from finn.custom_op.general.pwpolyfunction import (
    CLAMP_CFG,
    NUM_OCTAVES,
    SUPPORTED_FUNCS,
    _fit_coefficients,
)
from finn.util.basic import fifo_rtl_files
from finn.util.data_packing import array2hexstring
from finn.util.settings import get_settings

if TYPE_CHECKING:
    from onnx import GraphProto


def _rtllib_dir() -> Path:
    """Return the directory of the finn-rtllib pwpolyf HDL sources."""
    return Path(get_settings().finn_rtllib) / "pwpolyf" / "hdl"


def _float32_hex(value: float) -> str:
    """Return the upper-case hex bit pattern of ``value`` as an IEEE-754 FP32 number."""
    return array2hexstring(np.array([value]), DataType["FLOAT32"], 32, prefix="").upper()


def _generate_coeffs_pkg_data(
    K: int, degree: int = 2, num_samples: int = 1000  # noqa: N803
) -> str:
    """Generate the pwpolyf_pkg.sv package content for a given K value.

    Produces a SystemVerilog package with a func_cfg_t struct per activation
    function, containing clamping parameters and polynomial coefficients.

    Args:
        K: Number of top-mantissa subdivision bits.
        degree: Polynomial degree.
        num_samples: Samples per segment used to fit the coefficients.

    Returns:
        The SystemVerilog package source.

    """
    num_subs = 1 << K
    num_segs = 1 + 2 * NUM_OCTAVES * num_subs

    lines = []
    lines.append("// Auto-generated by pwpolyf_rtl.py - do not edit manually.")
    lines.append(
        f"// DEGREE={degree:d} K={K:d} NUM_OCTAVES={NUM_OCTAVES:d}  Segments: {num_segs:d}"
    )
    lines.append("")
    lines.append("package pwpolyf_pkg;")
    lines.append("")
    lines.append(f"    localparam int unsigned  DEGREE      = {degree:d};")
    lines.append(f"    localparam int unsigned  K           = {K:d};")
    lines.append(f"    localparam int unsigned  NUM_OCTAVES = {NUM_OCTAVES:d};")
    lines.append(f"    localparam int unsigned  NUM_SEGS    = {num_segs:d};")
    lines.append("")
    lines.append("    typedef struct {")
    lines.append("        int unsigned  neg_clamp;")
    lines.append("        int unsigned  pos_clamp;")
    lines.append("        bit           pos_passthrough;")
    lines.append("        int unsigned  coeffs[NUM_SEGS][DEGREE+1];")
    lines.append("    } func_cfg_t;")

    for func_name in SUPPORTED_FUNCS:
        cfg = CLAMP_CFG[func_name]
        coeffs = _fit_coefficients(func_name, K, degree=degree, num_samples=num_samples)
        label = func_name.upper()
        neg_hex = _float32_hex(cfg["neg_clamp"])
        pos_hex = _float32_hex(cfg["pos_clamp"])
        passthrough = 1 if cfg["pos_passthrough"] else 0

        lines.append("")
        lines.append(f"    localparam func_cfg_t  {label} = '{{")
        lines.append(f"        neg_clamp:       32'h{neg_hex},")
        lines.append(f"        pos_clamp:       32'h{pos_hex},")
        lines.append(f"        pos_passthrough: {passthrough:d},")
        lines.append("        coeffs: '{")
        for seg in range(num_segs):
            coeff_strs = [f"32'h{_float32_hex(coeffs[seg, c])}" for c in range(degree + 1)]
            comma = "," if seg < num_segs - 1 else ""
            lines.append(f"            '{{ {', '.join(coeff_strs)} }}{comma}\t// seg {seg:d}")
        lines.append("        }")
        lines.append("    };")

    lines.append("")
    lines.append("endpackage")
    lines.append("")
    return "\n".join(lines)


@register_custom_op
class PWPolyF_rtl(PWPolyF, RTLBackend):
    """RTL variant of PWPolyF, wraps the finn-rtllib pwpolyf IP."""

    def __init__(self, onnx_node: NodeProto, **kwargs: int) -> None:
        """Initialize instance."""
        super().__init__(onnx_node, **kwargs)

    def get_nodeattr_types(self) -> NodeAttrTypes:
        """Return node attribute types, combining PWPolyF and RTLBackend attributes."""
        my_attrs: NodeAttrTypes = {}
        my_attrs.update(PWPolyF.get_nodeattr_types(self))
        my_attrs.update(RTLBackend.get_nodeattr_types(self))
        return my_attrs

    def _generate_coeffs_pkg(self, num_samples: int = 1000) -> str:
        """Return the coefficient package source for this node's K and degree."""
        return _generate_coeffs_pkg_data(self.k, degree=self.degree, num_samples=num_samples)

    def generate_hdl(self, model: ModelWrapper, fpgapart: str, clk: float) -> None:  # noqa: ARG002
        """Render the pwpolyf wrapper template and write the coefficient package and RTL sources."""
        template_path = _rtllib_dir() / "pwpolyf_template_wrapper.v"
        code_gen_dir = cast("str", self.get_nodeattr("code_gen_dir_ipgen"))

        pe = self.pe
        topname = self.get_verilog_top_module_name()

        self.set_nodeattr("gen_top_module", topname)

        code_gen_dict = {
            "$MODULE_NAME_AXI_WRAPPER$": topname,
            "$TOP_MODULE$": topname,
            "$PE$": str(pe),
            "$FUNC$": f'"{self.func}"',
            "$IN_WIDTH$": str(pe * 32),
            "$OUT_WIDTH$": str(pe * 32),
        }

        # apply code generation to wrapper template
        template = template_path.read_text()
        for key, value in code_gen_dict.items():
            template = template.replace(key, str(value))
        (Path(code_gen_dir) / f"{topname}.v").write_text(template)

        # generate package with coefficients matching the node's K and degree
        pkg_data = self._generate_coeffs_pkg()
        (Path(code_gen_dir) / "pwpolyf_pkg.sv").write_text(pkg_data)

        self.set_nodeattr("ipgen_path", code_gen_dir)
        self.set_nodeattr("ip_path", code_gen_dir)

    def get_rtl_file_list(self, abspath: bool = False) -> list[str]:
        """Return the list of RTL files (package, core, wrapper and FIFO) for this node."""
        if abspath:
            code_gen_dir = cast("str", self.get_nodeattr("code_gen_dir_ipgen")) + "/"
            rtllib_dir = str(_rtllib_dir()) + "/"
        else:
            code_gen_dir = ""
            rtllib_dir = ""

        verilog_files = [
            code_gen_dir + "pwpolyf_pkg.sv",
            rtllib_dir + "pwpolyf.sv",
            code_gen_dir + cast("str", self.get_nodeattr("gen_top_module")) + ".v",
        ]
        return verilog_files + fifo_rtl_files(abspath=abspath)

    def execute_node(self, context: dict[str, np.ndarray], graph: "GraphProto") -> None:
        """Execute the node via Python (cppsim) or rtlsim depending on exec_mode."""
        mode = self.get_nodeattr("exec_mode")
        if mode == "cppsim":
            PWPolyF.execute_node(self, context, graph)
        elif mode == "rtlsim":
            RTLBackend.execute_node(self, context, graph)

    def code_generation_ipi(self) -> list[str]:
        """Construct and return the TCL for node instantiation in Vivado IPI."""
        cmd = [f"add_files -norecurse {f}" for f in self.get_rtl_file_list(abspath=True)]
        cmd.append(
            f"create_bd_cell -type module -reference {self.get_nodeattr('gen_top_module')} "
            f"{self.onnx_node.name}"
        )
        return cmd
