"""Transformations for per-node out-of-context (OOC) Vivado runs and their resource reports."""

import copy
import json
from concurrent.futures import ThreadPoolExecutor
from functools import partial
from onnx import NodeProto, helper
from pathlib import Path
from qonnx.core.modelwrapper import ModelWrapper
from qonnx.transformation.base import Transformation
from qonnx.util.basic import get_by_name, qonnx_make_model
from subprocess import CalledProcessError
from typing import cast

from finn.analysis.fpgadataflow.node_ooc_res_estimation import node_ooc_res_estimation
from finn.transformation.fpgadataflow.create_stitched_ip import CreateStitchedIP
from finn.util.basic import getHWCustomOp
from finn.util.exception import FINNInternalError, FINNSynthesisError, FINNUserError
from finn.util.fpgadataflow import is_hls_node, is_rtl_node
from finn.util.logging import log
from finn.util.settings import get_settings
from finn.util.vivado import run_ooc_pnr


class BuildNodeOOC(Transformation):
    """Implement every node on its own, out-of-context, in Vivado.

    Each node is cut out into a one-node model and wrapped into a Vivado project by
    CreateStitchedIP, reusing the IP generated by HLSSynthIP / PrepareIP. The project is
    synthesized out-of-context and optimized with opt_design, optionally followed by
    place & route. The project directory is stored in the ``ooc_proj_path`` node
    attribute; read the results with AnnotateNodeOOCResources or the
    node_ooc_res_estimation analysis pass.

    FINNLoop nodes are skipped, they keep their analytical estimates.
    """

    def __init__(self, fpgapart: str, clk_period_ns: float, place_and_route: bool = True) -> None:
        """Initialize the BuildNodeOOC transformation.

        Args:
            fpgapart: Target FPGA part
            clk_period_ns: Clock period in nanoseconds
            place_and_route: Run place & route after opt_design. If False, the flow stops
                after opt_design, which is much faster.
        """
        super().__init__()
        self.fpgapart = fpgapart
        self.clk_period_ns = clk_period_ns
        self.place_and_route = place_and_route

    @staticmethod
    def isolate_node(model: ModelWrapper, node: NodeProto) -> ModelWrapper:
        """Return a model that contains only the given node.

        The node is copied unchanged, so it keeps its generated IP (ip_path etc.) and
        CreateStitchedIP can reuse it without another HLS run. Unlike the isolation for
        node-by-node simulation, no dummy nodes are added and no attributes (mem_mode,
        ram_style, ...) are changed, since that would change the measured hardware.
        """
        initializers = []
        graph_inputs = []
        graph_outputs = []
        for tensor_name in [*node.input, *node.output]:
            if tensor_name == "":
                continue
            initializer = get_by_name(model.graph.initializer, tensor_name)
            if initializer is not None:
                # Weights, thresholds etc. keep their values, since the generated hardware
                # (and its resources) can depend on them
                initializers.append(copy.deepcopy(initializer))
                continue
            value_info = model.get_tensor_valueinfo(tensor_name)
            if value_info is None:
                raise FINNInternalError(
                    f"Tensor {tensor_name} of node {node.name} has no shape information, so "
                    "the node cannot be isolated for its out-of-context run. Run InferShapes "
                    "on the model first."
                )
            if tensor_name in node.input:
                graph_inputs.append(copy.deepcopy(value_info))
            else:
                graph_outputs.append(copy.deepcopy(value_info))

        graph = helper.make_graph(
            nodes=[copy.deepcopy(node)],
            name=f"ooc_{node.name}",
            inputs=graph_inputs,
            outputs=graph_outputs,
            initializer=initializers,
        )
        node_model = ModelWrapper(qonnx_make_model(graph, producer_name="finn"))

        # make_graph drops the FINN datatype annotations, but some ops derive interface
        # widths and code generation parameters from them, so restore them
        for tensor_name in [*node.input, *node.output]:
            if tensor_name != "":
                node_model.set_tensor_datatype(tensor_name, model.get_tensor_datatype(tensor_name))
        return node_model

    def implement_node(self, model: ModelWrapper, node: NodeProto) -> str:
        """Create the Vivado project for a single node and run the out-of-context flow.
        Returns the project directory."""
        node_model = self.isolate_node(model, node)
        # Project only (run_synth=False): run_ooc_pnr synthesizes it out-of-context
        node_model = node_model.transform(CreateStitchedIP(self.fpgapart, self.clk_period_ns))
        proj_dir = Path(cast("str", node_model.get_metadata_prop("vivado_stitch_proj")))
        block_name = cast("str", node_model.get_metadata_prop("vivado_stitch_vlnv")).split(":")[2]
        xpr_files = list(proj_dir.glob("*.xpr"))
        if len(xpr_files) != 1:
            raise FINNInternalError(
                f"Node {node.name}: expected exactly one Vivado project (*.xpr) in {proj_dir} "
                f"after CreateStitchedIP, found {len(xpr_files)}."
            )
        try:
            run_ooc_pnr(
                proj_dir,
                xpr_files[0].stem,
                block_name,
                self.clk_period_ns,
                place_and_route=self.place_and_route,
            )
        except CalledProcessError as e:
            raise FINNSynthesisError(
                f"Out-of-context Vivado run for node {node.name} failed. "
                f"Check the logs in {proj_dir}.",
                proj_dir / "vivado.log",
            ) from e
        log.info(f"Out-of-context run for node {node.name} finished.")
        return str(proj_dir)

    def apply(self, model: ModelWrapper) -> tuple[ModelWrapper, bool]:
        """Run the out-of-context flow for all nodes, in parallel."""
        nodes = []
        for node in model.graph.node:
            if node.op_type == "FINNLoop":
                log.warning(
                    f"Skipping FINNLoop node {node.name} in the per-node out-of-context run, "
                    "it keeps its analytical resource estimates."
                )
                continue
            if not (is_hls_node(node) or is_rtl_node(node)):
                raise FINNUserError(
                    f"Node {node.name} ({node.op_type}) is not an HLS or RTL node. Per-node "
                    "out-of-context runs need a specialized dataflow model, so run them on the "
                    "dataflow partition after step_specialize_layers and step_generate_hardware."
                )
            ip_path = cast("str", getHWCustomOp(node).get_nodeattr("ip_path"))
            if ip_path == "" or not Path(ip_path).is_dir():
                raise FINNUserError(
                    f"Node {node.name} has no generated IP (ip_path: '{ip_path}'). Per-node "
                    "out-of-context runs reuse the IPs from step_hw_ipgen, so "
                    "step_node_ooc_estimates must come after step_generate_hardware."
                )
            nodes.append(node)

        # Threads are sufficient, the work happens in Vivado subprocesses
        num_workers = max(1, get_settings().num_default_workers)
        log.info(f"Starting out-of-context runs for {len(nodes)} nodes with {num_workers} workers.")
        with ThreadPoolExecutor(max_workers=num_workers) as pool:
            futures = [pool.submit(self.implement_node, model, node) for node in nodes]
            proj_paths = [future.result() for future in futures]

        for node, proj_path in zip(nodes, proj_paths, strict=True):
            getHWCustomOp(node).set_nodeattr("ooc_proj_path", proj_path)
        return model, False


class AnnotateNodeOOCResources(Transformation):
    """Annotate each node with the resource utilization of its out-of-context run
    (``res_ooc`` node attribute, a JSON string). BuildNodeOOC must have run first."""

    def __init__(self, place_and_route: bool = True) -> None:
        """Initialize the AnnotateNodeOOCResources transformation.

        Args:
            place_and_route: Use the utilization after routing if True, otherwise the
                utilization after opt_design.
        """
        super().__init__()
        self.place_and_route = place_and_route

    def apply(self, model: ModelWrapper) -> tuple[ModelWrapper, bool]:
        """Read the reports and set the ``res_ooc`` node attributes."""
        res_dict = model.analysis(
            partial(node_ooc_res_estimation, place_and_route=self.place_and_route)
        )
        for node in model.graph.node:
            if node.name in res_dict:
                getHWCustomOp(node).set_nodeattr("res_ooc", json.dumps(res_dict[node.name]))
        return model, False
